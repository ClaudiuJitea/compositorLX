#!/usr/bin/env python3
"""Regenerate the embedded Vulkan 1.0 shader. Normal builds need no shader compiler."""
import argparse
import hashlib
from pathlib import Path
import shutil
import struct
import subprocess
import tempfile

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--compiler', default='glslangValidator')
parser.add_argument('--check', action='store_true', help='Check source hash without regenerating')
args = parser.parse_args()
root = Path(__file__).resolve().parent.parent
source = root / 'src/rendering/shaders/rendering.comp'
output = root / 'src/rendering/shaders/RenderingSpirv.h'
sha = hashlib.sha256(source.read_bytes()).hexdigest()
if args.check:
    if f'// Source SHA256: {sha}\n' not in output.read_text():
        raise SystemExit('Rendering shader source changed; regenerate RenderingSpirv.h')
    print('Rendering shader source matches generated header')
else:
    with tempfile.TemporaryDirectory() as tmp:
        binary = Path(tmp) / 'rendering.spv'
        subprocess.run([args.compiler, '-V', '--target-env', 'vulkan1.0', '-o', str(binary), str(source)], check=True)
        if validator := shutil.which('spirv-val'):
            subprocess.run([validator, '--target-env', 'vulkan1.0', str(binary)], check=True)
        data = binary.read_bytes()
    words = struct.unpack(f'<{len(data)//4}I', data)
    rows = ['    ' + ', '.join(f'0x{v:08x}' for v in words[i:i+8]) + ',' for i in range(0, len(words), 8)]
    output.write_text('// Generated by scripts/compile-rendering-shader.py; do not edit.\n'
                      f'// Source SHA256: {sha}\n#pragma once\n#include <cstdint>\n'
                      'namespace compositor {\ninline constexpr std::uint32_t renderingSpirv[] = {\n'
                      + '\n'.join(rows) + '\n};\n}\n')
